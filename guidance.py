def guidance_for(incident_type: str, subtype: str | None) -> dict:
    card = INFRA_OVERRIDES.get(subtype) if subtype else None
    card = card or GUIDANCE.get(incident_type) or GUIDANCE["Other"]
    return {"first_steps": list(card["first_steps"]), "safety": list(card["safety"])}


def dispatch_message(nearest: list) -> dict | None:
    """A simulated "help is on the way" line built from the nearest-station ETA."""
    if not nearest:
        return None
    best = min(nearest, key=lambda n: n["eta_min"])
    return {
        "message": "%s expected in approximately %d min (simulated)." % (best["resource"], best["eta_min"]),
        "eta_min": best["eta_min"],
        "resource": best["resource"],
    }
